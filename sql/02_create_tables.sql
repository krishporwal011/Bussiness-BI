CREATE TABLE stg_transaction_line (
    stg_row_id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    source_row_number    NUMBER NOT NULL,
    invoice_id           VARCHAR2(30),
    item_key             VARCHAR2(50),
    item_name            VARCHAR2(255),
    quantity             NUMBER,
    transaction_date     TIMESTAMP,
    unit_price           NUMBER(18, 6),
    customer_id          VARCHAR2(50),
    country              VARCHAR2(100),
    line_revenue         NUMBER(20, 6),
    is_cancellation      NUMBER(1),
    is_non_merchandise   NUMBER(1),
    is_exact_duplicate   NUMBER(1),
    is_test_transaction  NUMBER(1),
    exclusion_reason     VARCHAR2(50),
    is_retained          NUMBER(1),
    load_ts              TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT pk_stg_transaction_line PRIMARY KEY (stg_row_id),
    CONSTRAINT ck_stg_flags CHECK (
        is_cancellation IN (0, 1) AND is_non_merchandise IN (0, 1)
        AND is_exact_duplicate IN (0, 1) AND is_test_transaction IN (0, 1)
        AND is_retained IN (0, 1)
    )
);

CREATE TABLE dim_product (
    item_key       VARCHAR2(50) CONSTRAINT pk_dim_product PRIMARY KEY,
    item_name      VARCHAR2(255) NOT NULL,
    created_ts     TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE dim_customer (
    customer_key   VARCHAR2(50) CONSTRAINT pk_dim_customer PRIMARY KEY
);

CREATE TABLE dim_date (
    date_key       NUMBER(8) CONSTRAINT pk_dim_date PRIMARY KEY,
    calendar_date  DATE NOT NULL CONSTRAINT uq_dim_date UNIQUE,
    calendar_year  NUMBER(4) NOT NULL,
    calendar_month NUMBER(2) NOT NULL,
    month_name     VARCHAR2(20) NOT NULL,
    week_of_year   NUMBER(2) NOT NULL,
    day_of_month   NUMBER(2) NOT NULL
);

CREATE TABLE fact_transaction (
    basket_id          VARCHAR2(30) CONSTRAINT pk_fact_transaction PRIMARY KEY,
    transaction_date   TIMESTAMP NOT NULL,
    customer_key       VARCHAR2(50),
    country            VARCHAR2(100),
    CONSTRAINT fk_fact_txn_customer FOREIGN KEY (customer_key) REFERENCES dim_customer(customer_key)
);

CREATE TABLE fact_basket_item (
    basket_id       VARCHAR2(30) NOT NULL,
    item_key        VARCHAR2(50) NOT NULL,
    quantity        NUMBER(20, 6) NOT NULL,
    revenue         NUMBER(20, 6) NOT NULL,
    line_count      NUMBER NOT NULL,
    CONSTRAINT pk_fact_basket_item PRIMARY KEY (basket_id, item_key),
    CONSTRAINT fk_fbi_basket FOREIGN KEY (basket_id) REFERENCES fact_transaction(basket_id),
    CONSTRAINT fk_fbi_product FOREIGN KEY (item_key) REFERENCES dim_product(item_key),
    CONSTRAINT ck_fbi_quantity CHECK (quantity > 0),
    CONSTRAINT ck_fbi_revenue CHECK (revenue >= 0),
    CONSTRAINT ck_fbi_line_count CHECK (line_count > 0)
);

